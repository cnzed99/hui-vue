-- CORE-03 A only. No payment/dispatch/refund/cancel/reprint effects.
-- Trigger guards are installed by migrate-print-orders.py.
CREATE TABLE IF NOT EXISTS print_order (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_no VARCHAR(34) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL,
 store_id BIGINT NOT NULL,
 owner_user_id BIGINT NOT NULL,
 created_by_actor_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_by_actor_id BIGINT NOT NULL,
 source VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 simulation BIT NOT NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 total_amount VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payment_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 refund_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 delivery_mode VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 delivery_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 print_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version BIGINT NOT NULL,
 idempotency_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_order_no(order_no),
 UNIQUE KEY uk_print_order_idempotency(tenant_id,store_id,owner_user_id,idempotency_sha256),
 UNIQUE KEY uk_print_order_scope(tenant_id,store_id,owner_user_id,id),
 KEY idx_print_order_owner(tenant_id,store_id,owner_user_id,created_at_ms,id),
 CONSTRAINT fk_print_order_store FOREIGN KEY(tenant_id,store_id) REFERENCES print_store(tenant_id,id),
 CONSTRAINT chk_print_order_scope CHECK(tenant_id>0 AND store_id>0 AND owner_user_id>0),
 CONSTRAINT chk_print_order_actor CHECK(created_by_actor_type='STAFF' AND created_by_actor_id=owner_user_id),
 CONSTRAINT chk_print_order_demo CHECK(source='ADMIN_DEMO' AND simulation=b'1' AND currency='CNY'),
 CONSTRAINT chk_print_order_initial CHECK(order_state='OPEN' AND payment_state='UNPAID' AND refund_state='NONE'
  AND delivery_mode='NONE' AND delivery_state='NOT_APPLICABLE' AND print_state='NOT_CREATED' AND version=1),
 CONSTRAINT chk_print_order_created CHECK(created_at_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS print_order_item (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL,
 store_id BIGINT NOT NULL,
 owner_user_id BIGINT NOT NULL,
 quote_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 file_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 file_content_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 quote_snapshot_json JSON NOT NULL,
 amount VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sequence_no INT NOT NULL,
 created_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_order_item_quote(quote_id),
 UNIQUE KEY uk_print_order_item_sequence(order_id,sequence_no),
 KEY idx_print_order_item_owner(tenant_id,store_id,owner_user_id,order_id),
 CONSTRAINT fk_print_order_item_order FOREIGN KEY(tenant_id,store_id,owner_user_id,order_id)
  REFERENCES print_order(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT fk_print_order_item_quote FOREIGN KEY(quote_id) REFERENCES print_quote(id),
 CONSTRAINT chk_print_order_item_sequence CHECK(sequence_no=1),
 CONSTRAINT chk_print_order_item_created CHECK(created_at_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS print_order_event (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL,
 store_id BIGINT NOT NULL,
 owner_user_id BIGINT NOT NULL,
 event_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_id BIGINT NOT NULL,
 simulation BIT NOT NULL,
 aggregate_version BIGINT NOT NULL,
 created_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_order_event_version(order_id,aggregate_version),
 KEY idx_print_order_event_owner(tenant_id,store_id,owner_user_id,order_id,aggregate_version,id),
 CONSTRAINT fk_print_order_event_order FOREIGN KEY(tenant_id,store_id,owner_user_id,order_id)
  REFERENCES print_order(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT chk_print_order_event_actor CHECK(actor_type='STAFF' AND actor_id=owner_user_id),
 CONSTRAINT chk_print_order_event_initial CHECK(event_type='ORDER_CREATED' AND aggregate_version=1 AND simulation=b'1'),
 CONSTRAINT chk_print_order_event_created CHECK(created_at_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
