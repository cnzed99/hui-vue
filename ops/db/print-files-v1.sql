-- CORE-01 private file metadata. No original-site records, public URLs or secrets.
CREATE TABLE IF NOT EXISTS print_file (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    tenant_id BIGINT NOT NULL,
    store_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    idempotency_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    content_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    size_bytes BIGINT NOT NULL,
    page_count INT NULL,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    failure_code VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
    storage_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    expires_at_ms BIGINT NOT NULL,
    processing_started_at_ms BIGINT NULL,
    processing_attempts INT NOT NULL DEFAULT 0,
    blob_deleted_at_ms BIGINT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_print_file_idempotency (tenant_id, store_id, owner_user_id, idempotency_sha256),
    UNIQUE KEY uk_print_file_storage (storage_key),
    KEY idx_print_file_queue (status, created_at_ms),
    KEY idx_print_file_expiry (expires_at_ms, status),
    KEY idx_print_file_owner (tenant_id, store_id, owner_user_id, created_at_ms),
    CONSTRAINT chk_print_file_state CHECK (status IN ('UPLOADED','PROCESSING','READY','FAILED','DELETED')),
    CONSTRAINT chk_print_file_size CHECK (size_bytes > 0),
    CONSTRAINT chk_print_file_pages CHECK (page_count IS NULL OR page_count > 0),
    CONSTRAINT chk_print_file_owner CHECK (tenant_id > 0 AND store_id > 0 AND owner_user_id > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
