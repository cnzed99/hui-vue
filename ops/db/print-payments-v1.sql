-- CORE-04 subset: explicit synchronous simulated receipt, paired journal and queued job.
-- Apply ONLY with migrate-print-payments.py, which installs guards and the controlled order transition.
CREATE TABLE IF NOT EXISTS print_payment_receipt (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL, store_id BIGINT NOT NULL, owner_user_id BIGINT NOT NULL,
 provider VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 simulation BIT NOT NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 amount VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_id BIGINT NOT NULL,
 idempotency_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_payment_order(order_id),
 UNIQUE KEY uk_print_payment_idempotency(tenant_id,store_id,owner_user_id,idempotency_sha256),
 UNIQUE KEY uk_print_payment_scope(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT fk_print_payment_order FOREIGN KEY(tenant_id,store_id,owner_user_id,order_id) REFERENCES print_order(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT chk_print_payment_demo CHECK(provider='SIMULATED' AND state='SUCCEEDED' AND simulation=b'1' AND currency='CNY'),
 CONSTRAINT chk_print_payment_actor CHECK(actor_type='STAFF' AND actor_id=owner_user_id),
 CONSTRAINT chk_print_payment_created CHECK(created_at_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS print_simulated_journal (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 receipt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL, store_id BIGINT NOT NULL, owner_user_id BIGINT NOT NULL,
 entry_side VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 account_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 amount VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 simulation BIT NOT NULL,
 created_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_journal_side(receipt_id,entry_side),
 KEY idx_print_journal_owner(tenant_id,store_id,owner_user_id,order_id),
 CONSTRAINT fk_print_journal_receipt FOREIGN KEY(tenant_id,store_id,owner_user_id,receipt_id) REFERENCES print_payment_receipt(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT fk_print_journal_order FOREIGN KEY(tenant_id,store_id,owner_user_id,order_id) REFERENCES print_order(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT chk_print_journal_pair CHECK((entry_side='DEBIT' AND account_kind='SIMULATED_EXTERNAL_FUNDS') OR (entry_side='CREDIT' AND account_kind='SIMULATED_ORDER_RECEIPT')),
 CONSTRAINT chk_print_journal_demo CHECK(simulation=b'1' AND currency='CNY'),
 CONSTRAINT chk_print_journal_created CHECK(created_at_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS print_job (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 order_item_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payment_receipt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 file_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NOT NULL, store_id BIGINT NOT NULL, owner_user_id BIGINT NOT NULL,
 file_content_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 simulation BIT NOT NULL,
 generation INT NOT NULL,
 dispatch_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 print_result VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version BIGINT NOT NULL,
 attempt_count INT NOT NULL,
 terminal_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_owner VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_expires_at_ms BIGINT NULL,
 fencing_version BIGINT NOT NULL,
 created_at_ms BIGINT NOT NULL,
 updated_at_ms BIGINT NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_print_job_intent(order_item_id,generation),
 KEY idx_print_job_queue(tenant_id,store_id,owner_user_id,dispatch_state,created_at_ms,id),
 KEY idx_print_job_receipt(tenant_id,store_id,owner_user_id,payment_receipt_id),
 CONSTRAINT fk_print_job_order FOREIGN KEY(tenant_id,store_id,owner_user_id,order_id) REFERENCES print_order(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT fk_print_job_item FOREIGN KEY(order_item_id) REFERENCES print_order_item(id),
 CONSTRAINT fk_print_job_receipt FOREIGN KEY(tenant_id,store_id,owner_user_id,payment_receipt_id) REFERENCES print_payment_receipt(tenant_id,store_id,owner_user_id,id),
 CONSTRAINT chk_print_job_demo CHECK(source='ADMIN_DEMO' AND simulation=b'1'),
 CONSTRAINT chk_print_job_initial CHECK(generation=0 AND dispatch_state='QUEUED' AND print_result='NOT_REPORTED' AND version=1 AND attempt_count=0 AND fencing_version=0),
 CONSTRAINT chk_print_job_no_lease CHECK(terminal_id IS NULL AND lease_owner IS NULL AND lease_token_hash IS NULL AND lease_expires_at_ms IS NULL),
 CONSTRAINT chk_print_job_created CHECK(created_at_ms>0 AND updated_at_ms=created_at_ms)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
