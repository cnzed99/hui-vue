// Source/compile contract only; no HTTP, database or browser execution.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { createRequire } = require('node:module')
const path = require('node:path')
const frontend = createRequire(path.resolve(__dirname, '../../../package.json'))
const { parse, compileScript, compileTemplate } = frontend('vue/compiler-sfc')
for (const name of ['TerminalStatistics', 'PaperStatistics', 'PaperTotalStatistics', 'PaperDailyStatistics']) {
  const filename = path.join(__dirname, `${name}.vue`)
  const { descriptor, errors } = parse(fs.readFileSync(filename, 'utf8'), { filename })
  assert.deepEqual(errors, [])
  const script = compileScript(descriptor, { id: name })
  const template = compileTemplate({ source: descriptor.template.content, filename, id: name, compilerOptions: { bindingMetadata: script.bindings } })
  assert.deepEqual(template.errors, [])
}
const terminal = fs.readFileSync(path.join(__dirname, 'TerminalStatistics.vue'), 'utf8')
const paper = fs.readFileSync(path.join(__dirname, 'PaperStatistics.vue'), 'utf8')
const api = fs.readFileSync(path.join(__dirname, 'api.ts'), 'utf8')
assert.ok(terminal.includes('scenes.value = data.scenes'))
assert.ok(terminal.includes("ticket !== generation"))
assert.ok(paper.includes('ticket === generation'))
assert.ok(paper.includes('el-button link disabled'))
assert.ok(!/request\.(post|put|delete|patch)/.test(api))
assert.ok(api.includes('/print/statistics/terminal'))
assert.ok(api.includes("paper-${daily ? 'daily' : 'total'}"))
console.log('PASS four Vue SFC compilations, existing read-only API/scene/generation contracts')
